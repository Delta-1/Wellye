export function serviceWorkerSource({ cacheName, assets, shellHtml }) {
  return `// Generated by the build. Public Wellye static files only.
const CACHE = ${JSON.stringify(cacheName)};
const ASSETS = ${JSON.stringify(assets)};
const SHELL_URL = new URL('./', self.registration.scope).href;
const SHELL_HTML = ${JSON.stringify(shellHtml)};
async function precache() {
  const cache = await caches.open(CACHE);
  await cache.addAll(ASSETS);
  // The document and its asset list must belong to the exact same build.
  await cache.put(SHELL_URL, new Response(SHELL_HTML, {
    headers: { 'Content-Type': 'text/html; charset=utf-8' }
  }));
}
self.addEventListener('install', event => {
  event.waitUntil(precache());
  self.skipWaiting();
});
self.addEventListener('activate', event => {
  event.waitUntil((async () => {
    const previous = (await caches.keys()).filter(key => key.startsWith('wellye-') && key !== CACHE);
    // Existing tabs can still request the preceding build's lazy-loaded assets.
    await Promise.all(previous.slice(0, -2).map(key => caches.delete(key)));
    await self.clients.claim();
  })());
});
self.addEventListener('message', event => {
  if (event.data?.type === 'CACHE_OFFLINE') event.waitUntil(precache());
});
self.addEventListener('fetch', event => {
  const request = event.request;
  const url = new URL(request.url);
  if (request.method !== 'GET' || url.origin !== self.location.origin || !url.href.startsWith(self.registration.scope)) return;
  event.respondWith((async () => {
    const current = await caches.open(CACHE);
    // Never select an older document from a different cache version.
    if (request.mode === 'navigate') return (await current.match(SHELL_URL)) || fetch(request);
    const cached = (await current.match(request)) || (await caches.match(request));
    if (cached) return cached;
    const response = await fetch(request);
    if (response.ok) await current.put(request, response.clone());
    return response;
  })());
});
self.addEventListener('notificationclick', event => {
  event.notification.close();
  event.waitUntil(self.clients.matchAll({ type: 'window' }).then(list => list[0] ? list[0].focus() : self.clients.openWindow(self.registration.scope)));
});
`;
}
